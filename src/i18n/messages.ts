const helpTitles: Record<string, string> = {
  'Usage:': '用法：',
  'Options:': '选项：',
  'Arguments:': '参数：',
  'Commands:': '命令：',
  'Global Options:': '公共选项：',
};

export function helpText(value: string, language: Language): string {
  if (language === 'en') return value;
  return (
    helpTitles[value] ?? Object.values(messages).find((pair) => pair[1] === value)?.[0] ?? value
  );
}
